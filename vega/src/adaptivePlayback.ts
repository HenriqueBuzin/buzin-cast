/* global globalThis */
import * as Media from '@amazon-devices/react-native-w3cmedia';
import {DOMParser} from '@xmldom/xmldom';
import {decode, encode} from 'base-64';

// Browser globals required by the patched upstream player. Keep them local to
// this adapter; native media and XML parsing remain real SDK/library objects.
interface AdaptivePlayer {
  attach(player: Media.VideoPlayer): Promise<void>;
  load(url: string, position: number, mime: string): Promise<void>;
  destroy(): Promise<void>;
  configure(settings: Record<string, unknown>): void;
  addEventListener(event: string, callback: () => void): void;
  getNetworkingEngine(): {registerRequestFilter(filter: (type: number, request: {headers: Record<string, string>}) => void): void};
}
type Shaka = {
  Player: new () => AdaptivePlayer;
  polyfill: {installAll(): void};
  net: {NetworkingEngine: {registerScheme(scheme: string, plugin: unknown, priority: number, progress: boolean): void}; HttpFetchPlugin: {parse: unknown}};
};
let library: Shaka | undefined;
function loadLibrary(player: Media.VideoPlayer): Shaka {
  // The patched library targets a DOM-like environment while native rendering
  // stays in VideoPlayer. No vendor wrapper or sample app is redistributed.
  const scope = globalThis as unknown as Record<string, any>;
  scope.window = scope;
  scope.document = {
    createElement: () => player,
    getElementsByTagName: () => [player],
    addEventListener: () => {},
    removeEventListener: () => {},
  };
  scope.Element = scope.Element || class {};
  scope.HTMLElement = scope.HTMLElement || scope.Element;
  scope.Node = {TEXT_NODE: 3, CDATA_SECTION_NODE: 4};
  Object.assign(scope, {
    DOMParser,
    MediaSource: Media.MediaSource,
    SourceBuffer: Media.SourceBufferImpl,
    HTMLMediaElement: Media.HTMLMediaElement,
    TextDecoder: Media.TextDecoder,
    TextTrackCue: Media.VTTCue,
    VTTCue: Media.VTTCue,
    TextTrack: Media.TextTrackImpl,
    MediaError: Media.MediaError,
    crypto: Media.WebCrypto,
    atob: decode,
    btoa: encode,
  });
  scope.navigator.mediaCapabilities = {decodingInfo: Media.decodingInfo};
  scope.navigator.requestMediaKeySystemAccess = Media.requestMediaKeySystemAccess;
  scope.addEventListener = scope.addEventListener || (() => {});
  scope.removeEventListener = scope.removeEventListener || (() => {});
  if (!library) {
    // Generated by prepare_vega_shaka.py; excluded from source control.
    library = require('../generated/shaka-player.compiled.js') as Shaka;
    library.polyfill.installAll();
    for (const scheme of ['http', 'https']) {
      library.net.NetworkingEngine.registerScheme(scheme, library.net.HttpFetchPlugin.parse, 3, true);
    }
  }
  return library;
}

export function createAdaptivePlayback(player: Media.VideoPlayer, onError: () => void) {
  const shaka = loadLibrary(player);
  const engine = new shaka.Player();
  engine.addEventListener('error', onError);
  let closed = false;
  let closing: Promise<void> | undefined;
  return {
    async load(url: string, position: number, mime: string, headers: Record<string, string>) {
      await engine.attach(player);
      if (closed) {return;}
      engine.configure({abr: {enabled: true}, streaming: {bufferingGoal: 15}});
      engine.getNetworkingEngine().registerRequestFilter((_type, request) => {
        Object.assign(request.headers, headers);
      });
      await engine.load(url, position, mime);
    },
    stop() {
      closed = true;
      closing = closing || engine.destroy();
      return closing;
    },
  };
}
