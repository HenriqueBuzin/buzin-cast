"""Independent host TLS/protobuf witness for the API17 Cast experiment.

The Android test forwards bytes to its own LAN listener and exports only the
public certificate. The client pins that certificate; no identity is trusted
from a third-party receiver and no Google DeviceAuth certificate is supplied.
"""
import base64
import json
import socket
import ssl
import struct
import subprocess
import time
from cryptography import x509
from cryptography.hazmat.primitives.asymmetric import padding, rsa


HEARTBEAT = 'urn:x-cast:com.google.cast.tp.heartbeat'
AUTH = 'urn:x-cast:com.google.cast.tp.deviceauth'


def varint(value):
    out = bytearray()
    while value > 127:
        out.append((value & 127) | 128)
        value >>= 7
    return bytes(out) + bytes([value])


def message(namespace, payload, binary=False):
    def field(number, value):
        return varint(number * 8 + 2) + varint(len(value)) + value
    body = b'\x08\0' + field(2, b'host-test') + field(3, b'receiver-0') + field(4, namespace.encode())
    body += b'\x28' + bytes([int(binary)]) + field(7 if binary else 6, payload)
    return struct.pack('>I', len(body)) + body


def receive(stream):
    def exact(count):
        out = bytearray()
        while len(out) < count:
            chunk = stream.recv(count - len(out))
            if not chunk:
                raise AssertionError('Truncated TLS Cast response')
            out.extend(chunk)
        return bytes(out)
    size = struct.unpack('>I', exact(4))[0]
    if not 1 <= size <= 65536:
        raise AssertionError('Unbounded Cast response')
    body = exact(size)
    offset = 0
    def integer():
        nonlocal offset
        value = 0
        for shift in range(0, 35, 7):
            if offset >= len(body):
                raise AssertionError('Truncated protobuf integer')
            byte = body[offset]
            offset += 1
            value |= (byte & 127) << shift
            if byte < 128:
                return value
        raise AssertionError('Overlong protobuf integer')
    fields = {}
    while offset < len(body):
        key = integer()
        if key & 7 == 0:
            value = integer()
        elif key & 7 == 2:
            count = integer()
            if count > len(body) - offset:
                raise AssertionError('Truncated Cast field')
            value = body[offset:offset + count]
            offset += count
        else:
            raise AssertionError('Unsupported protobuf wire type')
        fields[key >> 3] = value
    if fields.get(1) != 0 or fields.get(3) != b'host-test':
        raise AssertionError('Cast response routing/version failed')
    return fields


def witness(port, certificate):
    # The sole trust anchor is the public key generated by this owned test app.
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    context.check_hostname = False
    context.verify_mode = ssl.CERT_NONE
    context.minimum_version = ssl.TLSVersion.TLSv1_2
    context.maximum_version = ssl.TLSVersion.TLSv1_2
    with socket.create_connection(('127.0.0.1', port), timeout=10) as plain:
        with context.wrap_socket(plain, server_hostname='buzin-cast.local') as tls:
            if tls.version() != 'TLSv1.2' or tls.getpeercert(binary_form=True) != certificate:
                raise AssertionError('Unexpected Cast TLS identity/protocol')
            parsed = x509.load_der_x509_certificate(certificate)
            public = parsed.public_key()
            if not isinstance(public, rsa.RSAPublicKey) or public.key_size < 2048 or parsed.issuer != parsed.subject:
                raise AssertionError('Invalid owned RSA certificate')
            if parsed.extensions.get_extension_for_class(x509.BasicConstraints).value.ca:
                raise AssertionError('Experimental Cast identity must not be a CA')
            usage = parsed.extensions.get_extension_for_class(x509.KeyUsage).value
            if not usage.digital_signature or not usage.key_encipherment or usage.key_cert_sign:
                raise AssertionError('Unexpected Cast certificate key usage')
            public.verify(parsed.signature, parsed.tbs_certificate_bytes, padding.PKCS1v15(), parsed.signature_hash_algorithm)
            tls.sendall(message(HEARTBEAT, b'{"type":"PING"}'))
            pong = receive(tls)
            if pong.get(4) != HEARTBEAT.encode() or json.loads(pong[6]).get('type') != 'PONG':
                raise AssertionError('Independent Cast heartbeat did not pass')
            tls.sendall(message(AUTH, b'\x0a\0', binary=True))
            auth = receive(tls)
            if auth.get(4) != AUTH.encode() or auth.get(7) != b'\x1a\x02\x08\0':
                raise AssertionError('Cast experiment did not reject DeviceAuth as specified')
            return {'protocol': tls.version(), 'cipher': tls.cipher()[0], 'certificate_pin': 'matched',
                    'rsa_bits': public.key_size, 'certificate_signature': 'verified', 'ca': False,
                    'protobuf_heartbeat': 'pass', 'device_auth': 'unsupported_error'}


def run_instrument(args, adb):
    command = [args.adb, '-P', str(args.adb_server_port), '-s', args.serial, 'shell', 'am', 'instrument', '-w',
               '-e', 'checks', 'castv2', args.package + '.test/io.buzincast.legacy.LegacyGestureChecks']
    local = None
    proof = None
    with (args.output / 'instrumentation.txt').open('wb') as output:
        process = subprocess.Popen(command, stdout=output, stderr=subprocess.STDOUT)
        try:
            deadline = time.monotonic() + 240
            while process.poll() is None:
                if time.monotonic() > deadline:
                    raise TimeoutError('Cast instrumentation exceeded its deadline')
                files = adb('shell', 'run-as', args.package, 'ls', 'files').split()
                if 'castv2-host-request' in files and proof is None:
                    remote = int(adb('shell', 'run-as', args.package, 'cat', 'files/castv2-host-port').strip())
                    certificate = base64.b64decode(adb('shell', 'run-as', args.package, 'cat', 'files/castv2-public.b64'))
                    parameters=adb('shell','run-as',args.package,'cat','files/castv2-parameters.json')
                    (args.output/'server-tls.json').write_text(parameters,encoding='utf-8')
                    local = int(adb('forward', 'tcp:0', 'tcp:' + str(remote)).strip())
                    proof = witness(local, certificate)
                    (args.output / 'host-tls.json').write_text(json.dumps(proof, indent=2) + '\n', encoding='utf-8')
                    adb('shell', 'run-as', args.package, 'mkdir', 'files/castv2-host-ack')
                # Old adbd needs far fewer short-lived shell processes than a
                # desktop client. The Android stage waits explicitly for ACK.
                time.sleep(1)
            if process.returncode != 0:
                raise AssertionError('Cast instrumentation process failed')
        finally:
            if process.poll() is None:
                process.kill()
                process.wait(timeout=10)
            if local is not None:
                adb('forward', '--remove', 'tcp:' + str(local))
    result = (args.output / 'instrumentation.txt').read_text(encoding='utf-8', errors='replace')
    if 'INSTRUMENTATION_RESULT: status=pass' in result and proof is None:
        raise AssertionError('Independent TLS/protobuf witness was skipped')
    return result
